'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {deploy,paths,BLOCK,SOURCE}=require('../scripts/install_sar.cjs');
const {hash}=require('../scripts/install_common.cjs');
const lua=process.env.AESA_LUA;
function fixture(t,content){const root=fs.mkdtempSync(path.join(os.tmpdir(),'aesa-sar-install-')),p=paths(root);t.after(()=>fs.rmSync(root,{recursive:true,force:true}));if(content!==undefined){fs.mkdirSync(path.dirname(p.export),{recursive:true});fs.writeFileSync(p.export,content);}return {root,p};}
test('Lua 5.1 sampler and callbacks', {skip:!lua&&'Set AESA_LUA to run Lua 5.1 integration'},()=>{
 const {spawnSync}=require('node:child_process');const r=spawnSync(lua,['tests/test_sar_export.lua'],{cwd:path.join(__dirname,'..'),encoding:'utf8',windowsHide:true});assert.equal(r.status,0,r.stderr+r.stdout);
});
test('Install/verify/repair/uninstall roundtrip preserves BOM, bytes, A/A and other tools', {skip:!lua&&'Set AESA_LUA to run Lua 5.1 integration'},t=>{
 const original=Buffer.from('\uFEFF-- SRS\r\n--[[ AESA EXPORT BEGIN ]]\r\n-- neighbor\r\n--[[ AESA EXPORT END ]]\r\n');
 const {root,p}=fixture(t,original);deploy(root,'install',{lua});deploy(root,'verify',{lua});const once=fs.readFileSync(p.export);deploy(root,'repair',{lua});assert.deepEqual(fs.readFileSync(p.export),once);
 assert.equal(fs.readFileSync(p.export,'utf8').split('AESA SAR BEGIN').length,2);assert.deepEqual(fs.readFileSync(p.export+'.bak-aesa'),original);
 deploy(root,'uninstall',{lua});assert.deepEqual(fs.readFileSync(p.export),original);assert.ok(!fs.existsSync(p.script));assert.ok(fs.existsSync(p.manifest+'.bak-aesa'));
});
test('Deploys the built runtime bundle, not the source entry', {skip:!lua&&'Set AESA_LUA to run Lua 5.1 integration'},t=>{
 const {root,p}=fixture(t,Buffer.from('-- user\r\n'));
 deploy(root,'install',{lua});
 const installed=fs.readFileSync(p.script);
 assert.equal(hash(installed),hash(fs.readFileSync(SOURCE)),'installed bytes must be the built bundle');
 assert.match(installed.toString('utf8'),/^-- DO NOT EDIT -- generated by scripts\/build_runtime\.cjs/);
 assert.match(installed.toString('utf8'),/AESA_RUNTIME = \{/);
 assert.match(installed.toString('utf8'),/AESA_SAR = \{[\s\S]*?profile_data = ProfileData/);
 assert.match(installed.toString('utf8'),/-- ---- entry: src\/export\/aesa_sar_export\.lua ----/);
 const manifest=JSON.parse(fs.readFileSync(p.manifest,'utf8'));
 assert.equal(manifest.source,'dist/dev/aesa_sar_export.lua');
 assert.equal(manifest.script_hash,hash(installed));
});
test('Fresh Export is removed on uninstall; later foreign additions are preserved', {skip:!lua&&'Set AESA_LUA to run Lua 5.1 integration'},t=>{
 const a=fixture(t);deploy(a.root,'install',{lua});deploy(a.root,'uninstall',{lua});assert.ok(!fs.existsSync(a.p.export));
 const b=fixture(t,Buffer.from("print('original')"));deploy(b.root,'install',{lua});fs.appendFileSync(b.p.export,"print('later')\n");deploy(b.root,'uninstall',{lua});assert.equal(fs.readFileSync(b.p.export,'utf8'),"print('original')\n\nprint('later')\n");
});
test('Unknown same-name file is never overwritten even if identical to source',t=>{
 const {root,p}=fixture(t,Buffer.from('-- user'));fs.mkdirSync(path.dirname(p.script),{recursive:true});fs.writeFileSync(p.script,'-- unknown');
 assert.throws(()=>deploy(root,'install',{lua}),/Unknown/);assert.equal(fs.readFileSync(p.export,'utf8'),'-- user');assert.equal(fs.readFileSync(p.script,'utf8'),'-- unknown');
});
test('Modified installed script blocks repair and uninstall', {skip:!lua&&'Set AESA_LUA to run Lua 5.1 integration'},t=>{
 const {root,p}=fixture(t,Buffer.from('-- user'));deploy(root,'install',{lua});fs.appendFileSync(p.script,'\n-- local edits');const raw=fs.readFileSync(p.export);
 for(const action of ['repair','uninstall'])assert.throws(()=>deploy(root,action,{lua}),/modified/);
 assert.deepEqual(fs.readFileSync(p.export),raw);assert.ok(fs.existsSync(p.manifest));
});
test('Broken/duplicated markers and unowned loader block are not edited',t=>{
 for(const content of ['--[[ AESA SAR BEGIN ]]\n','--[[ AESA SAR END ]]\n--[[ AESA SAR BEGIN ]]\n',BLOCK+'\n',BLOCK+'\n'+BLOCK+'\n']){
  const {root,p}=fixture(t,Buffer.from(content));assert.throws(()=>deploy(root,'install',{lua}));assert.equal(fs.readFileSync(p.export,'utf8'),content);
 }
});
test('Syntax failure prevents any deployment mutation',t=>{
 const {root,p}=fixture(t,Buffer.from('-- user'));assert.throws(()=>deploy(root,'install',{lua:path.join(root,'missing-lua.exe')}),/syntax check failed/);
 assert.equal(fs.readFileSync(p.export,'utf8'),'-- user');assert.ok(!fs.existsSync(p.script));assert.ok(!fs.existsSync(p.export+'.bak-aesa'));
});
